<?php

namespace App\Tests\Functional\Admin;

use App\DataFixtures\AppFixtures;
use App\Entity\Tariff;
use App\Entity\User;
use App\Enum\TariffCode;
use App\Tests\Functional\FunctionalTestCase;

/**
 * The tariff catalogue is fixed — the four approved pricing categories
 * (docs/DECISIONS.md Q5), and only those, enforced by the database.
 *
 * The screen is a read-only reference: no form, no edit route, no way to add
 * or remove a category from the interface.
 */
class TariffCatalogueTest extends FunctionalTestCase
{
    private \Symfony\Bundle\FrameworkBundle\KernelBrowser $client;

    protected function setUp(): void
    {
        $this->client = $this->bootWithFixtures();
        $this->client->loginUser($this->entityManager()
            ->getRepository(User::class)
            ->findOneBy(['email' => AppFixtures::USER_ADMIN_EMAIL]));
    }

    public function test_the_catalogue_holds_exactly_the_four_approved_categories(): void
    {
        $em = $this->entityManager();
        /** @var list<Tariff> $tariffs */
        $tariffs = $em->getRepository(Tariff::class)->findBy([]);

        self::assertCount(4, $tariffs);

        $codes = array_map(static fn (Tariff $tariff): string => $tariff->getCode(), $tariffs);
        sort($codes);

        self::assertSame(['FULL', 'GROUP', 'INVITATION', 'REDUCED'], $codes);

        foreach ($tariffs as $tariff) {
            // The name is generated by the database — it must equal the label.
            self::assertSame(TariffCode::from($tariff->getCode())->label(), $tariff->getName());
            // Only the reduced tariff requires a supporting document (Q5).
            self::assertSame(TariffCode::Reduced->value === $tariff->getCode(), $tariff->requiresEligibilityProof());
        }
    }

    public function test_the_reference_screen_renders_the_catalogue_read_only(): void
    {
        $crawler = $this->client->request('GET', '/admin/tariffs');

        self::assertResponseIsSuccessful();
        self::assertSelectorTextContains('.page-header__title', 'Tariffs');

        foreach (['FULL', 'REDUCED', 'GROUP', 'INVITATION'] as $code) {
            self::assertSelectorTextContains('.table', $code);
        }

        // No form and no edit link — the screen writes nothing.
        self::assertCount(0, $crawler->filter('form'));
        self::assertCount(0, $crawler->filter('a[href*="edit"]'));
    }

    public function test_the_edit_route_no_longer_exists(): void
    {
        $em = $this->entityManager();
        $tariff = $em->getRepository(Tariff::class)->findOneBy(['code' => 'REDUCED']);
        self::assertInstanceOf(Tariff::class, $tariff);

        $this->client->request('GET', '/admin/tariffs/'.$tariff->getId().'/edit');

        self::assertResponseStatusCodeSame(404);
    }

    public function test_no_form_can_change_a_tariff(): void
    {
        $this->client->request('POST', '/admin/tariffs', ['_token' => 'x', 'name' => 'Cheap']);

        // The route answers GET only — a POST is refused.
        self::assertResponseStatusCodeSame(405);
    }

    public function test_the_database_refuses_a_fifth_category(): void
    {
        $em = $this->entityManager();

        try {
            $em->getConnection()->executeStatement("INSERT INTO tariff (code) VALUES ('STUDENT')");
            self::fail('The database accepted a fifth tariff category.');
        } catch (\Doctrine\DBAL\Exception\DriverException $exception) {
            self::assertStringContainsString('ck_tariff_code', $exception->getMessage());
        }
    }

    public function test_the_name_cannot_be_edited_at_the_database_level(): void
    {
        $em = $this->entityManager();

        try {
            $em->getConnection()->executeStatement("UPDATE tariff SET name = 'Cheap tickets' WHERE code = 'FULL'");
            self::fail('The database accepted an edit of the generated name.');
        } catch (\Doctrine\DBAL\Exception\DriverException $exception) {
            self::assertStringContainsStringIgnoringCase('generated column', $exception->getMessage());
        }
    }
}
